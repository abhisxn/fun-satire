import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const INVENTORY_PATH = resolve(ROOT, "src/config/visualTokens.json");
const CSS_PATH = resolve(ROOT, "src/styles/tokens.css");

const inventory = JSON.parse(await readFile(INVENTORY_PATH, "utf8"));

function kebab(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function cssValue(path, value) {
  if (typeof value !== "number") return value;
  if (path.startsWith("motion.duration.")) return `${value}ms`;
  if (
    path.includes("Opacity") ||
    path.includes("zIndex") ||
    path.includes("Scale") ||
    path.endsWith("multiplier") ||
    path.endsWith("Multiplier")
  ) {
    return String(value);
  }
  return `${value}px`;
}

function flatten(value, path = []) {
  return Object.entries(value).flatMap(([key, child]) => {
    const nextPath = [...path, key];
    if (child !== null && typeof child === "object") return flatten(child, nextPath);
    return [[`--${nextPath.map(kebab).join("-")}`, cssValue(nextPath.join("."), child)]];
  });
}

function generateCss() {
  const semantic = flatten(inventory)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");

  return `/* Generated by npm run tokens:generate. Do not edit directly. */
:root {
${semantic}

  /* Compatibility aliases for existing Canvas-art and HUD consumers. */
  --color-cream: #EDE7DD;
  --color-slate: #5B7A8C;
  --color-sage: #6D7A5E;
  --color-ink: #2A2420;
  --color-coral: #E8A9A0;
  --font-display: var(--typography-display-family);
  --font-mono: var(--typography-mono-family);
  --duration-fast: ${inventory.motion.duration.fast}ms;
  --duration-base: ${inventory.motion.duration.base}ms;
  --duration-slow: ${inventory.motion.duration.slow}ms;
  --ease-protest: ${inventory.motion.ease.protest};
  --ease-charge: ${inventory.motion.ease.charge};
  --ease-fade: ${inventory.motion.ease.fade};
  --ease-spring: ${inventory.motion.ease.spring};
  --z-canvas: ${inventory.overlay.zIndex.canvas};
  --z-grain: ${inventory.overlay.zIndex.grain};
  --z-hud: ${inventory.overlay.zIndex.hud};
  --grain-opacity: ${inventory.atmosphere.grainOpacity};
  --grain-tile-url: ${inventory.atmosphere.grainTileUrl};
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --duration-fast: 0ms;
    --duration-base: 0ms;
    --duration-slow: 0ms;
    --motion-multiplier: var(--motion-reduced-multiplier);
  }
}
`;
}

const expected = generateCss();

if (process.argv.includes("--check")) {
  const actual = await readFile(CSS_PATH, "utf8").catch(() => "");
  if (actual !== expected) {
    console.error("src/styles/tokens.css is out of date. Run npm run tokens:generate.");
    process.exitCode = 1;
  }
} else {
  await writeFile(CSS_PATH, expected);
}
