import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const INVENTORY_PATH = resolve(ROOT, "src/config/visualTokens.json");
const CSS_PATH = resolve(ROOT, "src/styles/tokens.css");

const inventory = JSON.parse(await readFile(INVENTORY_PATH, "utf8"));
const { canvasArt, numericUnits, ui } = inventory;

function kebab(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

export function formatNumericToken(path, value) {
  const unit = numericUnits[path];
  if (unit === undefined) {
    throw new Error(`No numeric unit metadata for "${path}".`);
  }
  if (unit === "unitless") return String(value);
  if (unit === "px" || unit === "ms") return `${value}${unit}`;
  throw new Error(`Unsupported numeric unit "${unit}" for "${path}".`);
}

function flatten(value, path = []) {
  return Object.entries(value).flatMap(([key, child]) => {
    const nextPath = [...path, key];
    if (child !== null && typeof child === "object") return flatten(child, nextPath);
    const tokenPath = nextPath.join(".");
    const cssValue = typeof child === "number" ? formatNumericToken(tokenPath, child) : child;
    return [[`--${nextPath.map(kebab).join("-")}`, cssValue]];
  });
}

function assertExhaustiveNumericUnits() {
  const numericPaths = new Set(
    flattenValues(ui)
      .filter(([, value]) => typeof value === "number")
      .map(([path]) => path),
  );
  for (const path of Object.keys(numericUnits)) {
    if (!numericPaths.has(path)) {
      throw new Error(`Numeric unit metadata references non-numeric token "${path}".`);
    }
  }
}

function flattenValues(value, path = []) {
  return Object.entries(value).flatMap(([key, child]) => {
    const nextPath = [...path, key];
    if (child !== null && typeof child === "object") return flattenValues(child, nextPath);
    return [[nextPath.join("."), child]];
  });
}

export function generateCss() {
  assertExhaustiveNumericUnits();
  const semantic = flatten(ui)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  const canvasAliases = Object.entries(canvasArt)
    .map(([name, value]) => `  --color-${kebab(name)}: ${value};`)
    .join("\n");

  return `/* Generated by npm run tokens:generate. Do not edit directly. */
:root {
${semantic}

  /* Compatibility aliases for existing Canvas-art and HUD consumers. */
${canvasAliases}
  --font-display: var(--typography-display-family);
  --font-mono: var(--typography-mono-family);
  --duration-fast: ${ui.motion.duration.fast}ms;
  --duration-base: ${ui.motion.duration.base}ms;
  --duration-slow: ${ui.motion.duration.slow}ms;
  --ease-protest: ${ui.motion.ease.protest};
  --ease-charge: ${ui.motion.ease.charge};
  --ease-fade: ${ui.motion.ease.fade};
  --ease-spring: ${ui.motion.ease.spring};
  --z-canvas: ${ui.overlay.zIndex.canvas};
  --z-grain: ${ui.overlay.zIndex.grain};
  --z-hud: ${ui.overlay.zIndex.hud};
  --grain-opacity: ${ui.atmosphere.grainOpacity};
  --grain-tile-url: ${ui.atmosphere.grainTileUrl};
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --duration-fast: 0ms;
    --duration-base: 0ms;
    --duration-slow: 0ms;
    --motion-multiplier: var(--motion-reduced-multiplier);
  }
}
`;
}

async function main() {
  const expected = generateCss();
  if (process.argv.includes("--check")) {
    const actual = await readFile(CSS_PATH, "utf8").catch(() => "");
    if (actual !== expected) {
      console.error("src/styles/tokens.css is out of date. Run npm run tokens:generate.");
      process.exitCode = 1;
    }
  } else {
    await writeFile(CSS_PATH, expected);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
